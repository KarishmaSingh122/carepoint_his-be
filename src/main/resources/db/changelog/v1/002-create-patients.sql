    patient_address_district               VARCHAR(255),
    patient_address_village_town_city      VARCHAR(255),

    patient_comm_address_address           VARCHAR(255),
    patient_comm_address_pincode           VARCHAR(255),
    patient_comm_address_state             VARCHAR(255),
