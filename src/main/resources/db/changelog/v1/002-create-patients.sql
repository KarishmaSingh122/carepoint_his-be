CREATE SEQUENCE IF NOT EXISTS patient_mr_sequence
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE IF NOT EXISTS patients
(
    patient_id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    abha_id                                VARCHAR(14) NOT NULL UNIQUE,
    patient_name                           VARCHAR(200),
    date_of_birth                          DATE,
    age                                    VARCHAR(255),
    phone                                  VARCHAR(20),
    gender                                 VARCHAR(20),
    relation                               VARCHAR(50),

    patient_mr_number                      VARCHAR(50) NOT NULL UNIQUE,

    is_comm_address_same_as_card_address   BOOLEAN,
    is_child_registration                  BOOLEAN,

    patient_address_address                VARCHAR(255),
    patient_address_pincode                VARCHAR(255),
    patient_address_state                  VARCHAR(255),
    patient_address_district               VARCHAR(255),
    patient_address_village_town_city      VARCHAR(255),

    patient_comm_address_address           VARCHAR(255),
    patient_comm_address_pincode            VARCHAR(255),
    patient_comm_address_state              VARCHAR(255),
    patient_comm_address_district           VARCHAR(255),
    patient_comm_address_village_town_city  VARCHAR(255),

    contact_person_name                    VARCHAR(255),
    contact_person_relation_description    VARCHAR(255),
    contact_person_relation_code           VARCHAR(255),
    contact_person_relation_url             VARCHAR(255),
    contact_person_address                 VARCHAR(255),
    contact_person_mobile_number           VARCHAR(255),
    contact_person_gender                  SMALLINT,

    subscriber_abha_number                 VARCHAR(255),
    subscriber_name                        VARCHAR(255),
    subscriber_gender                      VARCHAR(255),
    subscriber_mob                         VARCHAR(255),
    subscriber_dob                         DATE,
    subscriber_subscriber_id               VARCHAR(255),

    active                                 BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

--rollback DROP TABLE patients;
--rollback DROP SEQUENCE patient_mr_sequence;
