    contact_person_name                    VARCHAR(255),
    contact_person_relation_description    VARCHAR(255),
    contact_person_relation_code           VARCHAR(255),
    contact_person_relation_url            VARCHAR(255),
    contact_person_address                 VARCHAR(255),
    contact_person_mobile_number           VARCHAR(255),
    contact_person_gender                  SMALLINT,

    subscriber_abha_number                 VARCHAR(255),
    subscriber_name                        VARCHAR(255),
    subscriber_gender                      VARCHAR(255),
    subscriber_mob                         VARCHAR(255),
    subscriber_dob                         DATE,
    subscriber_subscriber_id               VARCHAR(255),
    active                                 BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
