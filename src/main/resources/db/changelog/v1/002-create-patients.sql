    abha_id                                VARCHAR(14) NOT NULL UNIQUE,
    patient_name                           VARCHAR(200),
    date_of_birth                          DATE,
    age                                    VARCHAR(255),
    phone                                  VARCHAR(20),
    gender                                 VARCHAR(20),
    relation                               VARCHAR(50),
    patient_mr_number                      VARCHAR(50),

    is_comm_address_same_as_card_address   BOOLEAN,
